"""
IOFlow agent pack — the ONE definition of IOFlow's design agents.

``agents/<name>.md`` holds each agent's prompt plus a small front matter
(``name``, ``adk_id``, ``description``, ``tools``). Every surface that runs an
IOFlow design agent reads it from here instead of keeping its own copy:

- the IOFlow Assistant's Google ADK agents (``backend/agent/*/agent.py``) and
  its Claude Code mode (``dev_agent_runtime/api_routes.py``);
- the Claude Code plugin (``ioflow-plugin/agents/*.md`` are GENERATED by
  ``scripts/build_plugin_agents.py`` and held identical by
  ``tests/test_agent_pack.py``);
- external agents such as Twasta's Ask-AI, through ``GET /api/mcp/agent-pack``.

Every tool an agent names is a tool of the MCP bridge (``/api/mcp/tools``),
which is the one tool surface all of those surfaces use.
"""
from __future__ import annotations

import hashlib
import os
from functools import lru_cache
from typing import Any, Dict, List, Optional

PACK_SCHEMA = 1
AGENTS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "agents")


def _parse(text: str, source: str) -> Dict[str, Any]:
    if not text.startswith("---\n"):
        raise ValueError(f"{source}: missing front matter")
    end = text.index("\n---\n", 4)
    meta: Dict[str, Any] = {}
    for line in text[4:end].splitlines():
        if not line.strip():
            continue
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip()
    for required in ("name", "description", "tools"):
        if not meta.get(required):
            raise ValueError(f"{source}: front matter needs '{required}'")
    meta["tools"] = [t.strip() for t in meta["tools"].split(",") if t.strip()]
    meta["prompt"] = text[end + len("\n---\n"):].strip() + "\n"
    return meta


@lru_cache(maxsize=1)
def _load() -> Dict[str, Any]:
    agents: List[Dict[str, Any]] = []
    digest = hashlib.sha256()
    for filename in sorted(os.listdir(AGENTS_DIR)):
        if not filename.endswith(".md"):
            continue
        path = os.path.join(AGENTS_DIR, filename)
        with open(path, "r", encoding="utf-8") as f:
            text = f.read()
        digest.update(filename.encode() + b"\0" + text.encode("utf-8") + b"\0")
        agents.append(_parse(text, filename))
    return {
        "schema": PACK_SCHEMA,
        "version": digest.hexdigest()[:16],
        "tool_surface": "ioflow-mcp-bridge",
        "agents": agents,
    }


def load_pack() -> Dict[str, Any]:
    """The whole pack: ``{schema, version, tool_surface, agents: [...]}``."""
    return _load()


def get_agent(name: str) -> Optional[Dict[str, Any]]:
    """One agent by pack name (``flow-designer``) or ADK id (``flow_designer``)."""
    for agent in _load()["agents"]:
        if name in (agent["name"], agent.get("adk_id")):
            return agent
    return None


def agent_prompt(name: str) -> str:
    """The prompt of one agent — what the ADK agents use as their instruction."""
    agent = get_agent(name)
    if agent is None:
        raise KeyError(f"No IOFlow agent named '{name}' in the agent pack")
    return agent["prompt"]


def render_plugin_agent(agent: Dict[str, Any]) -> str:
    """The Claude Code plugin's ``agents/<name>.md`` for one pack agent."""
    return (
        "---\n"
        f"name: {agent['name']}\n"
        f"description: {agent['description']}\n"
        "---\n\n"
        "<!-- GENERATED from backend/agent_pack/agents/"
        f"{agent['name']}.md by backend/scripts/build_plugin_agents.py — edit the pack, not this file. -->\n\n"
        + agent["prompt"]
    )
