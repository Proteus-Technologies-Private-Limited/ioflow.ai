#!/bin/bash
# IOFlow Plugin Setup Script
# Configures environment variables for Claude Desktop / Claude Code
set -e

SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
PLUGIN_DIR="$(dirname "$SCRIPT_DIR")"
PROJECT_ROOT="$(dirname "$PLUGIN_DIR")"

BASE_URL="${IOFLOW_BASE_URL:-http://localhost:7001}"

echo "IOFlow Plugin Setup"
echo "==================="
echo ""
echo "Step 1: Add these to your ~/.zshrc (or ~/.bashrc):"
echo ""
echo "  export IOFLOW_HOME=\"$PROJECT_ROOT\""
echo "  export IOFLOW_BASE_URL=\"$BASE_URL\""
echo ""
echo "Step 2: Generate an API key from the IOFlow frontend:"
echo "  Go to Settings > API Keys > Create"
echo "  Then add to your ~/.zshrc:"
echo ""
echo "  export IOFLOW_API_KEY=\"ioflow_your_key_here\""
echo ""
echo "Step 3: Restart your terminal (or run: source ~/.zshrc)"
echo ""
echo "Step 4: Install the plugin in Claude Desktop:"
echo ""
echo "  Option A - Local marketplace (for Cowork tab):"
echo "    In Claude Desktop, click + > Plugins > Add plugin"
echo "    Or from CLI:"
echo "      /plugin marketplace add $PROJECT_ROOT/ioflow-marketplace"
echo "      /plugin install ioflow@ioflow-plugins"
echo ""
echo "  Option B - Direct CLI testing:"
echo "    claude --plugin-dir $PLUGIN_DIR"
echo ""
echo "============================================"
echo "Available skills after installing:"
echo "  /ioflow:list-apps          - List seed applications"
echo "  /ioflow:create-seed-app    - Create a new seed application"
echo "  /ioflow:design-flow        - Design a new automation flow"
echo "  /ioflow:edit-flow          - Edit an existing flow"
echo ""
echo "Available agents (auto-invoked or via /agents):"
echo "  ioflow:seed-app-designer   - Full seed application management"
echo "  ioflow:flow-designer       - Design flows from scratch"
echo "  ioflow:flow-editor         - Edit and debug existing flows"
